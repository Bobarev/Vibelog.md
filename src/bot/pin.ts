/**
 * Генерация пин-кода привязки чата (VL-34).
 *
 * Пин печатается только в консоль запущенного `vibelog bot` — привязка
 * доступна тому, кто запустил процесс. Однорожден на сессию: при рестарте
 * генерируется новый.
 */

import { randomInt } from 'node:crypto';

/** Возвращает 6-значный пин-код («000000»–«999999») строкой. */
export function generatePin(): string {
  return String(randomInt(0, 1000000)).padStart(6, '0');
}
